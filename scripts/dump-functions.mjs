/**
 * scripts/dump-functions.mjs
 *
 * Dumps all custom SQL functions / RPC procedures from the Supabase project
 * into  supabase/migrations/functions.sql
 *
 * Uses the Supabase Management API (no Docker required).
 *
 * Setup – one-time:
 *   1. Go to https://supabase.com/dashboard/account/tokens
 *   2. Generate a new personal access token
 *   3. Add to .env.local:  SUPABASE_ACCESS_TOKEN=sbp_xxxx…
 *
 * Usage:
 *   node scripts/dump-functions.mjs
 *   npm run db:dump:functions
 */

import { readFileSync, writeFileSync, existsSync } from "fs";
import { resolve, dirname, join } from "path";
import { fileURLToPath } from "url";
import { homedir } from "os";

const __dir = dirname(fileURLToPath(import.meta.url));
const root  = resolve(__dir, "..");
const OUT   = resolve(root, "supabase", "migrations", "functions.sql");

// ── Load env files ──────────────────────────────────────────────────────────
function loadEnv(filename) {
  try {
    for (const line of readFileSync(resolve(root, filename), "utf8").split(/\r?\n/)) {
      const t = line.trim();
      if (!t || t.startsWith("#")) continue;
      const eq = t.indexOf("=");
      if (eq === -1) continue;
      const k = t.slice(0, eq).trim();
      const v = t.slice(eq + 1).trim().replace(/^['"]|['"]$/g, "");
      if (!(k in process.env)) process.env[k] = v;
    }
  } catch { /* not found */ }
}
loadEnv(".env.local");
loadEnv(".env");

// ── Extract project ref from NEXT_PUBLIC_SUPABASE_URL ──────────────────────
const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL ?? "";
const projectRef  = supabaseUrl.match(/https:\/\/([^.]+)\.supabase\.co/)?.[1];

if (!projectRef) {
  console.error("Could not determine project ref from NEXT_PUBLIC_SUPABASE_URL.");
  process.exit(1);
}

// ── Find access token ───────────────────────────────────────────────────────
// Priority: env var → CLI config files
function findCLIToken() {
  const candidates = [
    join(homedir(), "AppData", "Roaming", "supabase", "access-token"),
    join(homedir(), "AppData", "Local",   "supabase", "access-token"),
    join(homedir(), ".config", "supabase", "access-token"),
    join(homedir(), ".supabase", "access-token"),
  ];
  for (const p of candidates) {
    if (existsSync(p)) {
      return readFileSync(p, "utf8").trim();
    }
  }
  return null;
}

const accessToken =
  process.env.SUPABASE_ACCESS_TOKEN ??
  process.env.SUPABASE_TOKEN ??
  findCLIToken();

if (!accessToken) {
  console.error(`
ERROR: No Supabase access token found.

To fix this, do ONE of the following:

  Option A (recommended) – add to .env.local:
    SUPABASE_ACCESS_TOKEN=sbp_xxxxxxxxxxxx
    Get a token at: https://supabase.com/dashboard/account/tokens

  Option B – log in with the CLI:
    npx supabase login
`);
  process.exit(1);
}

// ── SQL query – fetch all custom function definitions ──────────────────────
const SQL = `
SELECT
  n.nspname                   AS schema,
  p.proname                   AS name,
  pg_get_functiondef(p.oid)   AS definition
FROM   pg_catalog.pg_proc        p
JOIN   pg_catalog.pg_namespace   n ON n.oid = p.pronamespace
WHERE  n.nspname NOT IN ('pg_catalog','information_schema','pg_toast')
  AND  p.prokind IN ('f','p')
  AND  NOT EXISTS (
         SELECT 1
         FROM   pg_catalog.pg_depend  d
         JOIN   pg_catalog.pg_extension e ON d.refobjid = e.oid
         WHERE  d.objid = p.oid AND d.deptype = 'e'
       )
ORDER  BY n.nspname, p.proname;
`;

// ── Call Management API ────────────────────────────────────────────────────
console.log(`Fetching functions for project ${projectRef} …`);

let rows;
try {
  const res = await fetch(
    `https://api.supabase.com/v1/projects/${projectRef}/database/query`,
    {
      method:  "POST",
      headers: {
        "Authorization": `Bearer ${accessToken}`,
        "Content-Type":  "application/json",
      },
      body: JSON.stringify({ query: SQL }),
    }
  );

  if (!res.ok) {
    const body = await res.text();
    console.error(`Management API error ${res.status}: ${body}`);
    process.exit(1);
  }

  rows = await res.json();
} catch (e) {
  console.error("Network error calling Management API:", e.message);
  process.exit(1);
}

if (!Array.isArray(rows) || rows.length === 0) {
  console.warn("No function definitions returned.");
  process.exit(0);
}

// ── Write output ───────────────────────────────────────────────────────────
const header = [
  `-- Generated by: scripts/dump-functions.mjs`,
  `-- Date:         ${new Date().toISOString()}`,
  `-- Project:      ${projectRef}`,
  `-- Functions:    ${rows.length}`,
  `-- ============================================================`,
  "",
  "",
].join("\n");

const body = rows
  .map(r => `-- schema: ${r.schema}\n${r.definition.trimEnd()}\n;`)
  .join("\n\n");

writeFileSync(OUT, header + body + "\n", "utf8");
console.log(`\n✓ Wrote ${rows.length} function(s) → supabase/migrations/functions.sql`);
